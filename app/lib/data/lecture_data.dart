/// 민법 특강 카드 데이터 — 홈 화면 가로 스크롤 그리드와 "더보기" 전체 그리드 화면이 공유한다.
class LectureItem {
  /// 표지 이미지가 아직 없는 특강(예: 경영학 '유형자산과 감가상각', 경제법 특강)은 null —
  /// 이 경우 [styleKey]로 subjectStyleOf에서 아이콘·색상을 가져와 아이콘형 카드로 대체 표시한다.
  final String? imageAsset;
  final String title;
  final List<String> keyPoints;
  final String subjectId;
  final String subjectName;
  final String category;

  /// 같은 category 안에서 더 세부적으로 필터링할 하위 유형(subTopic). 지정하지 않으면
  /// 해당 category 전체 문제를 보여준다.
  final String? subTopic;

  /// imageAsset이 없을 때 subjectStyleOf(styleKey)로 아이콘·색상을 조회하기 위한 키.
  final String? styleKey;

  const LectureItem({
    this.imageAsset,
    required this.title,
    required this.keyPoints,
    required this.subjectId,
    required this.subjectName,
    required this.category,
    this.subTopic,
    this.styleKey,
  });
}

