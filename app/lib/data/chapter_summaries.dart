/// 아직 요약이 없는 챕터는 null을 반환 — 화면에서 "준비 중"으로 안내한다.
List<String>? summaryFor(String subjectId, String topic) {
  for (final s in chapterSummaries) {
    if (s.subjectId == subjectId && s.topic == topic) return s.keyPoints;
  }
  return null;
}

