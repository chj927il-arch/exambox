/// topic 문자열은 topic_stats.dart의 TopicStat.topic과 정확히 일치해야 한다.
class ChapterSummary {
  final String subjectId;
  final String topic;
  final List<String> keyPoints;

  const ChapterSummary({required this.subjectId, required this.topic, required this.keyPoints});
